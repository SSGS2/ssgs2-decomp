// Radians in [-pi, pi]; sign comes from a.z*b.x - a.x*b.z. Y is ignored.
// Zero cross chooses the negative branch, including the antiparallel -pi case.
// Return the signed angle between XZ projections; nearly zero vectors give zero.
float Vector_SignedAngleXZ(const float* a, const float* b) {
    Vec3f da, cb, ca, cb0;
    register float ax = a[0], ay = kFloat_0_Matrix, az = a[2];
    ((volatile Vec3f*)&ca)->x = ax;
    ((volatile Vec3f*)&ca)->y = ay;
    ((volatile Vec3f*)&ca)->z = az;
    da = ca;
    cb0.x = b[0];
    cb0.y = kFloat_0_Matrix;
    cb0.z = b[2];
    cb = cb0;
    float lenA = Math_SquareRootApprox(Fn8004BA28Dot(&ca, &da));
    float lenB = Math_SquareRootApprox(Fn8004BA28Dot(&cb, &cb));
    if (Fn8004BA28Tiny(lenA) || Fn8004BA28Tiny(lenB))
        return kFloat_0_Matrix;
    double dot = Fn8004BA28Dot(&da, &cb);
    float t = (float)dot / ((float)lenA * (float)lenB);
    double clamped;
    if (t < kFloat_neg1_MatrixAngle)
        clamped = kFloat_neg1_MatrixAngle;
    else if (t > kFloat_1_matrixQuaternion)
        clamped = kFloat_1_matrixQuaternion;
    else
        clamped = t;
    float result = (float)acos(clamped);
    float cross = FP_FMSUBS(a[2], b[0], a[0] * b[2]);
    return (cross > kFloat_0_Matrix) ? result : -result;
}
