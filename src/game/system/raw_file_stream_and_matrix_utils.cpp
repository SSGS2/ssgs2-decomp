    destination[1] = FP_FMADDS_ADD_FIRST(FP_FMADDS(left[0], right[1], left[1] * right[4]), left[2], right[7]);
    destination[2] = FP_FMADDS_ADD_FIRST(FP_FMADDS(left[0], right[2], left[1] * right[5]), left[2], right[8]);
