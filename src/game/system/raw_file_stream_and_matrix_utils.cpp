// Clear a negative sign by conditional negation, retaining the original bit test.
static inline void MakeFloatAbsolute(float& value) {
    float saved = value;
    unsigned int bits = *(unsigned int*)&saved;
    if (bits & 0x80000000u)
        value = -value;
}

// Require every component difference to be strictly less than the supplied tolerance.
int Vec3_NearlyEqualWithTolerance(const float* a, const float* b, float tolerance) {
    float d;
    int close;
    d = a[0] - b[0];
    MakeFloatAbsolute(d);
    close = d < tolerance;
    if (close) {
        d = a[1] - b[1];
        MakeFloatAbsolute(d);
        close = d < tolerance;
        if (close) {
            d = a[2] - b[2];
            MakeFloatAbsolute(d);
            close = d < tolerance;
            // Original unit 0x8004A814: all three components must pass the tolerance test.
            if (close)
                return 1;
        }
    }
    return 0;
}
