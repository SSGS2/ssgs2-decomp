// mode 1=current, 2=end; EVERY other mode treats offset as an absolute byte position.
// Seek relative to start/current/end and clamp the cursor to the file byte range.
void cFileRaw_SeekCursor(Fn8004AED8Arg* arg, int offset, int mode) {
    switch (mode) {
    case kSeekCurrent:
        offset += arg->index;
        break;
    case kSeekEnd:
        offset += arg->length;
        break;
    case 0:
    case 3:
        break;
    default:
        break;
    }
    int length = arg->length;
    if (offset > length)
        offset = length;
    arg->index = offset & (((-offset) & ~offset) >> 31);
}

// dst must hold the positive clamped count. A negative count is returned unchanged
// without copying or moving the cursor; callers should supply nonnegative counts.
// Read up to the remaining byte count and advance the stream cursor.
int cFileRaw_ReadBytes(Fn8004AE60Arg* arg, void* dst, int count) {
    int available = arg->length - arg->index;
    if (count > available)
        count = available;
    if (count > 0) {
        memcpy(dst, arg->data + arg->index, count);
        arg->index += count;
    }
    return count;
}

