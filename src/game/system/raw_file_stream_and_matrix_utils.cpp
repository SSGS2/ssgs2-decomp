// Convert an orthogonal 3-by-3 basis to a quaternion using its trace or largest diagonal.
void Matrix3x3_ToQuat(float* out, const float* m) {
    float tr = m[8] + (m[0] + m[4]);
    if (tr > kFloat_0_Matrix) {
        float s = (float)sqrt(kFloat_1_matrixQuaternion + tr);
        float k = kFloat_0_5_Quaternion / s;
        out[3] = kFloat_0_5_Quaternion * s;
        out[0] = k * (m[7] - m[5]);
        out[1] = k * (m[2] - m[6]);
        out[2] = k * (m[3] - m[1]);
        return;
    }
    int axis;
    float a = m[0];
    float b = m[4];
    float c = m[8];
    if (a > b) {
        if (a > c)
            axis = 0;
        else
            axis = 2;
    } else if (b > c)
        axis = 1;
    else
        axis = 2;
    switch (axis) {
    case 0: {
        float t = Math_SquareRootApprox(kFloat_1_matrixQuaternion + m[0] - m[4] - m[8]);
        float k = kFloat_0_5_Quaternion / t;
        out[0] = kFloat_0_5_Quaternion * t;
        out[1] = k * (m[3] + m[1]);
        out[2] = k * (m[2] + m[6]);
        out[3] = k * (m[7] - m[5]);
        break;
    }
    case 1: {
        float u = kFloat_1_matrixQuaternion - m[0];
        float t = Math_SquareRootApprox(u + m[4] - m[8]);
        float k = kFloat_0_5_Quaternion / t;
        out[1] = kFloat_0_5_Quaternion * t;
        out[0] = k * (m[1] + m[3]);
        float w = m[2] - m[6];
        out[3] = k * w;
        out[2] = k * (m[5] + m[7]);
        break;
    }
    case 2: {
        float t = Math_SquareRootApprox(m[8] + (kFloat_1_matrixQuaternion - m[0] - m[4]));
        float half = kFloat_0_5_Quaternion;
        float k = half / t;
        out[0] = k * (m[6] + m[2]);
        out[1] = k * (m[5] + m[7]);
        float w = m[3] - m[1];
        out[2] = half * t;
        out[3] = k * w;
        break;
    }
    }
}
