            if (cap > oldCap) {
                data = (char*)appMallocDummy__FUl(cap);
            } else {
                try {
                    data = (char*)appMallocDummy__FUl(cap);
                } catch (...) {
                    return;
                }
            }
            newLong = 1;
            old = isLong ? s->data : (char*)s + 1;
