// Expand quaternion components into a 3-by-3 rotation matrix.
void Quat_ToMatrix3x3(float* out, float* in) {
    // Phase 1: load [x,y,z,w] and form doubled products. Reused accumulators
    // retain the original operation/store order (including possible input aliasing).
    register float diagonalZ, diagonalY, xySum, xyDifference, xzSum, yzProduct;
    register float twiceW, z, twiceY, yThenWY, twiceX, x, twiceXY, twiceWZ;
    xySum = kFloat_2_Bitmap;
    yThenWY = in[1];
    twiceY = xySum * yThenWY;
    z = in[2];
    x = in[0];
    diagonalZ = in[3];
    diagonalY = xySum * z;
    twiceX = xySum * x;
    yzProduct = kFloat_1_matrixQuaternion;
    xyDifference = twiceY * yThenWY; // 2*y*y
    diagonalY *= z;                  // 2*z*z
    twiceW = xySum * diagonalZ;
    diagonalZ = twiceX * x; // 2*x*x
    twiceXY = twiceX * yThenWY;
    // Phase 2: diagonal terms and XY pair, then XZ/YZ pairs in row-major storage.
    xySum = xyDifference + diagonalY;
    diagonalY = diagonalZ + diagonalY;
    diagonalZ = diagonalZ + xyDifference;
    twiceWZ = twiceW * z;
    xzSum = yzProduct - xySum;         // m00 = 1 - 2*(yy+zz)
    diagonalY = yzProduct - diagonalY; // m11 = 1 - 2*(xx+zz)
    xyDifference = twiceXY - twiceWZ;
    diagonalZ = yzProduct - diagonalZ; // m22 = 1 - 2*(xx+yy)
    out[0] = xzSum;
    xySum = twiceXY + twiceWZ;
    yThenWY = (twiceW * yThenWY); // 2*w*y
    out[4] = diagonalY;
    out[1] = xyDifference;
    xzSum = twiceX * z; // 2*x*z
    float product = twiceY * z;
    yzProduct = product;
    twiceW *= x; // 2*w*x
    out[3] = xySum;
    xyDifference = xzSum + yThenWY; // m02
    diagonalY = xzSum - yThenWY;    // m20
    xySum = yzProduct - twiceW;     // m12
    out[8] = diagonalZ;
    float sum = yzProduct + twiceW;
    diagonalZ = sum; // m21
    out[2] = xyDifference;
    out[5] = xySum;
    out[6] = diagonalY;
    out[7] = diagonalZ;
}
