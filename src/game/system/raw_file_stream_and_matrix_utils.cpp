// Custom scanner, not scanf: returns 1 after walking format, 0 on several EOF
// paths (even after earlier outputs were written); literals are not matched.
// %d/%u/%x write 32-bit integers, %f/%g write float, %s writes a whitespace token,
// %n reads up to tab/CR/LF (spaces included). Case variants agree.
// arguments is a va_list cursor; callers provide correctly typed output pointers.
// No widths/buffer bounds: numeric tokens must fit 127 bytes plus NUL and string
// outputs must be large enough. Hex has optional '-', but no 0x-prefix handling.
// Scan numeric/string conversions; return unread lookahead except CR, consumed as a line terminator.
int Stream_VScanFormat(ScanStream* stream, const char* format, Fn8004A814Out* arguments) {
    int formatIndex;
    int currentByte;
    int formatLength;
    char conversionBuffer[0x80];
    int integerValue;
    float floatValue;
    int tokenState;
    int conversionState;

    currentByte = -1;
    formatLength = (int)strlen(format);
    formatIndex = 0;

    // Phase 1: acquire a token for each conversion, retaining one lookahead byte.
    while (formatIndex < formatLength) {
        if (format[formatIndex] == '%') {
            if (currentByte == -1) {
                currentByte = stream->get();
                if (currentByte == -1)
                    return 0;
            }
            while (currentByte == '\n' || currentByte == '\t' || currentByte == '\r' || currentByte == ' ') {
                currentByte = stream->get();
                if (currentByte == -1)
                    return 0;
            }
            switch ((signed char)format[formatIndex + 1]) {
            case 'x':
            case 'X': {
                conversionState = 0;
                integerValue = 0;
                while ((currentByte >= '0' && currentByte <= '9') || (currentByte >= 'a' && currentByte <= 'f') ||
                       (currentByte >= 'A' && currentByte <= 'F') || (conversionState == 0 && currentByte == '-')) {
                    if (currentByte == '-') {
                        conversionState |= 1;
                    } else {
                        if (currentByte >= 'a')
                            currentByte -= 0x20;
                        integerValue =
                            (integerValue << 4) + (currentByte <= '9' ? currentByte - 0x30 : currentByte - 0x37);
                    }
                    currentByte = stream->get();
                    if (currentByte == -1)
                        return 0;
                }
                if (conversionState != 0)
                    integerValue = -integerValue;
                memcpy(*(void**)__va_arg(arguments, 1), &integerValue, 4);
                break;
            }
            case 'F':
            case 'G':
            case 'f':
            case 'g': {
                conversionState = 0;
                tokenState = 0;
                while ((currentByte >= '0' && currentByte <= '9') || (conversionState == 0 && currentByte == '-') ||
                       (tokenState == 0 && currentByte == '.')) {
                    if (currentByte == '.')
                        tokenState = 1;
                    conversionBuffer[conversionState] = (char)currentByte;
                    currentByte = stream->get();
                    if (currentByte == -1) {
                        ++conversionState;
                        break;
                    }
                    ++conversionState;
                }
                conversionBuffer[conversionState] = 0;
                floatValue = (float)atof(conversionBuffer);
                memcpy(*(void**)__va_arg(arguments, 1), &floatValue, 4);
                break;
            }
            case 'D':
            case 'U':
            case 'd':
            case 'u': {
                tokenState = 0;
                while ((currentByte >= '0' && currentByte <= '9') || (tokenState == 0 && currentByte == '-')) {
                    conversionBuffer[tokenState] = (char)currentByte;
                    currentByte = stream->get();
                    if (currentByte == -1) {
                        ++tokenState;
                        break;
                    }
                    ++tokenState;
                }
                conversionBuffer[tokenState] = 0;
                integerValue = String_ParseDecimalInt(conversionBuffer);
                memcpy(*(void**)__va_arg(arguments, 1), &integerValue, 4);
                break;
            }
            case 'S':
            case 's': {
                char* destination = (char*)*(void**)__va_arg(arguments, 1);
                char* writeCursor = destination;
                tokenState = 0;
                while (currentByte != '\n' && currentByte != '\t' && currentByte != '\r' && currentByte != ' ' &&
                       currentByte != -1) {
                    *writeCursor = (char)currentByte;
                    currentByte = stream->get();
                    if (currentByte == -1) {
                        ++tokenState;
                        break;
                    }
                    ++tokenState;
                    ++writeCursor;
                }
                destination[tokenState] = 0;
                break;
            }
            case 'N':
            case 'n': {
                char* destination = (char*)*(void**)__va_arg(arguments, 1);
                char* writeCursor = destination;
                tokenState = 0;
                while (currentByte != '\n' && currentByte != '\t' && currentByte != '\r' && currentByte != -1) {
                    *writeCursor = (char)currentByte;
                    currentByte = stream->get();
                    if (currentByte == -1) {
                        ++tokenState;
                        break;
                    }
                    ++tokenState;
                    ++writeCursor;
                }
                destination[tokenState] = 0;
                break;
            }
            default:
                break;
            }
        }
        ++formatIndex;
    }
    // Phase 2: put lookahead back, except CR (consumed as a line terminator).
    if (currentByte != -1 && currentByte != '\r')
        stream->seek(-1, 1);
    return 1;
}
